"""
ARD — schemas/contracts.py
===========================
Pydantic schemas serving as strict A2A (Agent-to-Agent) contracts.

Every message passed between agents is wrapped in an A2AMessageEnvelope.
Every agent produces output conforming to AgentOutput.
The LangGraph shared state is defined as ARDState (TypedDict).

Design Rule: If an agent can't produce a valid AgentOutput, it MUST
raise an exception — the circuit breaker in ard_graph.py catches it.
"""

import datetime
from uuid import uuid4
from typing import TypedDict, Optional, Dict, Any, List
from pydantic import BaseModel, Field


# ──────────────────────────────────────────────────────────────────────────────
# A2A PROTOCOL: INTER-AGENT MESSAGE ENVELOPE
# ──────────────────────────────────────────────────────────────────────────────

class A2AMessageEnvelope(BaseModel):
    """
    Standardized, traceable message envelope for all Agent-to-Agent communications.
    Every node-to-node communication in the LangGraph is logged as one of these.
    """
    trace_id: str
    sender_agent: str
    target_agent: str
    timestamp: str = Field(
        default_factory=lambda: datetime.datetime.utcnow().isoformat() + "Z"
    )
    payload: Dict[str, Any]
    status: str = "success"          # "success" | "circuit_breaker" | "schema_error"
    error_message: Optional[str] = None


# ──────────────────────────────────────────────────────────────────────────────
# AGENT OUTPUT CONTRACT
# ──────────────────────────────────────────────────────────────────────────────

class AgentOutput(BaseModel):
    """
    Strict output schema all three specialist agents must conform to.
    The Synthesis Agent validates each agent's output against this before proceeding.
    """
    agent_name: str = Field(..., description="Canonical name of the producing agent")
    signal: str = Field(
        ...,
        description=(
            "Concise, actionable signal generated by the agent. "
            "E.g., 'ECB hawkish pivot: +25bps expected at March meeting' or "
            "'Merger XYZ: Anti-trust risk elevated — CFIUS parallel review initiated'"
        )
    )
    confidence: float = Field(
        ..., ge=0.0, le=1.0,
        description="Agent's self-assessed confidence in the signal (0.0–1.0)"
    )
    evidence: str = Field(
        ...,
        description="Direct quote or paraphrase from source data supporting the signal"
    )
    source_url: Optional[str] = Field(
        None,
        description="URL or identifier of the primary source document"
    )
    asset_class: Optional[str] = Field(
        None,
        description="Relevant asset class: 'Rates', 'Equities', 'FX', 'Credit', 'Commodities', 'Multi'"
    )


# ──────────────────────────────────────────────────────────────────────────────
# SYNTHESIS OUTPUT CONTRACT
# ──────────────────────────────────────────────────────────────────────────────

class SynthesisOutput(BaseModel):
    """
    Strict output schema for the Synthesis & Drafting Agent.
    The Groundedness Guardrail validates this before writing the final report.
    """
    headline: str = Field(
        ...,
        description="One-sentence punchy research headline (max 15 words)"
    )
    executive_summary: str = Field(
        ...,
        description="2–3 sentence executive summary of the combined research signals"
    )
    macro_commentary: str = Field(
        ...,
        description="Detailed macro analysis (Central Bank signals, inflation, rate path)"
    )
    event_driven_commentary: str = Field(
        ...,
        description="Detailed M&A / anti-trust / special situations analysis"
    )
    trade_ideas: List[str] = Field(
        ...,
        description="List of 1–3 specific, actionable trade ideas for institutional clients"
    )
    risk_flags: List[str] = Field(
        ...,
        description="List of 1–3 key risks or tail risks the analyst should verify"
    )


# ──────────────────────────────────────────────────────────────────────────────
# LANGGRAPH SHARED STATE
# ──────────────────────────────────────────────────────────────────────────────

class ARDState(TypedDict):
    """
    The central, shared memory object passed between every LangGraph node.
    All nodes read from and write back to this TypedDict.
    """
    # ── Input ─────────────────────────────────────────────────
    trigger_query: str                          # Raw news / query triggering the pipeline

    # ── Agent Outputs ──────────────────────────────────────────
    agent_outputs: Dict[str, Dict[str, Any]]    # Keyed by agent_name, value = AgentOutput.dict()

    # ── RAG ───────────────────────────────────────────────────
    retrieved_chunks: List[Dict[str, Any]]      # Top-k chunks from Pinecone hybrid search

    # ── Synthesis ─────────────────────────────────────────────
    synthesis_draft: Optional[Dict[str, Any]]   # SynthesisOutput.dict() or None
    groundedness_score: float                   # 0.0–1.0
    synthesis_retry_count: int                  # Tracks self-correction attempts

    # ── Final Output ───────────────────────────────────────────
    final_report: Optional[Dict[str, Any]]      # Written to output JSON file
    hitl_required: bool                         # True → escalate to human analyst
    hitl_reason: Optional[str]                  # Explanation for HITL escalation

    # ── Tracing & Audit ───────────────────────────────────────
    trace_id: str                               # Global session trace ID
    trace_history: List[Dict[str, Any]]         # All A2A envelope logs


# ──────────────────────────────────────────────────────────────────────────────
# HELPERS
# ──────────────────────────────────────────────────────────────────────────────

def new_trace_id() -> str:
    return f"ard_{uuid4().hex[:8]}"


def build_envelope(
    state: ARDState,
    sender: str,
    target: str,
    payload: Dict[str, Any],
    status: str = "success",
    error: Optional[str] = None,
) -> Dict[str, Any]:
    """Create a typed A2A envelope and return it as a plain dict for the trace_history list."""
    env = A2AMessageEnvelope(
        trace_id=state.get("trace_id", "unknown"),
        sender_agent=sender,
        target_agent=target,
        payload=payload,
        status=status,
        error_message=error,
    )
    return env.model_dump()
